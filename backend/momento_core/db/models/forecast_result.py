"""
ForecastResult model for prediction outputs.

Represents forecast results generated by the Forecast Engine including
predicted values, confidence intervals, and model metadata.
"""

from sqlalchemy import String, Float, Text, ForeignKey, Index
from sqlalchemy.orm import Mapped, mapped_column
from momento_core.db.base import BaseModel, TimestampMixin
from typing import Optional


class ForecastResult(BaseModel, TimestampMixin):
    """
    Forecast result from predictive modeling.
    
    This table stores forecast predictions with confidence intervals
    and model metadata for accuracy tracking and visualization.
    
    Attributes:
        id: Unique identifier
        model_type: Type of forecasting model used (e.g., 'arima', 'prophet')
        horizon_periods: Number of periods predicted into the future
        confidence_level: Confidence level for intervals (e.g., 0.95 for 95%)
        predictions: JSON string containing prediction points
        accuracy_score: Model accuracy score (if evaluated)
        training_duration_seconds: Time taken to train the model
        evaluated_at: Timestamp when forecast was evaluated against actuals
        metadata: JSON string with additional model metadata
    """
    
    __tablename__ = "forecast_results"
    
    model_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        index=True,
        doc="Type of forecasting model (arima, prophet, linear_regression, etc.)"
    )
    
    horizon_periods: Mapped[int] = mapped_column(
        nullable=False,
        doc="Number of periods predicted into the future"
    )
    
    confidence_level: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        default=0.95,
        doc="Confidence level for intervals (e.g., 0.95 for 95%)"
    )
    
    predictions: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="JSON string containing prediction points with timestamps and values"
    )
    
    accuracy_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        doc="Model accuracy score (if evaluated against actuals)"
    )
    
    training_duration_seconds: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        doc="Time taken to train the model in seconds"
    )
    
    evaluated_at: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
        doc="UTC timestamp when forecast was evaluated against actuals"
    )
    
    meta_data: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        doc="JSON string with additional model metadata (parameters, feature importance, etc.)"
    )
    
    # Indexes for common query patterns
    __table_args__ = (
        Index("idx_forecast_results_model_type", "model_type"),
        Index("idx_forecast_results_created_at", "created_at"),
    )
    
    def __repr__(self) -> str:
        """String representation of ForecastResult."""
        return f"<ForecastResult(id={self.id}, model_type={self.model_type}, horizon={self.horizon_periods})>"
